/**
 * Ion Engine - Handles ionization and charge balancing for ionic compounds
 */

import { METALS, NONMETALS, POLYATOMIC_IONS, IONIC_RADII } from './ionicDatabase';

export interface Ion {
  id: string;
  element?: string; // For monoatomic ions
  polyatomicId?: string; // For polyatomic ions (key in POLYATOMIC_IONS)
  charge: number; // +1, -2, etc.
  count: number; // Number of this ion in the formula unit
  position: { x: number; y: number };
  type: 'cation' | 'anion' | 'polyatomic';
  isIonized: boolean; // Has the electron transfer occurred?
}

export interface IonicCompound {
  id: string;
  cations: Ion[];
  anions: Ion[];
  formula: string;
  isBalanced: boolean; // Total charge = 0?
  formulaUnit?: { cation: string; anion: string; cationCount: number; anionCount: number };
}

/**
 * Create a neutral atom (not yet ionized)
 */
export function createAtom(element: string, position: { x: number; y: number }): Ion {
  const elementInfo = METALS[element] || NONMETALS[element];
  if (!elementInfo) {
    throw new Error(`Unknown element: ${element}`);
  }

  const isMetal = !!METALS[element];

  return {
    id: `ion-${Date.now()}-${Math.random()}`,
    element,
    charge: 0, // Not ionized yet
    count: 1,
    position,
    type: isMetal ? 'cation' : 'anion',
    isIonized: false,
  };
}

/**
 * Create a polyatomic ion
 */
export function createPolyatomicIon(polyatomicId: string, position: { x: number; y: number }): Ion {
  const polyatomic = POLYATOMIC_IONS[polyatomicId];
  if (!polyatomic) {
    throw new Error(`Unknown polyatomic ion: ${polyatomicId}`);
  }

  return {
    id: `polyion-${Date.now()}-${Math.random()}`,
    polyatomicId,
    charge: polyatomic.charge,
    count: 1,
    position,
    type: 'polyatomic',
    isIonized: true, // Polyatomic ions are already charged
  };
}

/**
 * Ionize an atom (transfer electrons to form an ion)
 */
export function ionizeAtom(ion: Ion, oxidationState: number): Ion {
  if (ion.polyatomicId) {
    // Polyatomic ions are already ionized
    return ion;
  }

  return {
    ...ion,
    charge: oxidationState,
    isIonized: true,
  };
}

/**
 * Calculate the lowest common multiple for charge balancing
 */
function lcm(a: number, b: number): number {
  return Math.abs(a * b) / gcd(a, b);
}

function gcd(a: number, b: number): number {
  a = Math.abs(a);
  b = Math.abs(b);
  while (b) {
    const temp = b;
    b = a % b;
    a = temp;
  }
  return a;
}

/**
 * Balance charges between cation and anion to create neutral compound
 * Returns the subscripts needed for each ion
 */
export function balanceCharges(
  cationCharge: number,
  anionCharge: number
): { cationCount: number; anionCount: number } {
  if (cationCharge <= 0 || anionCharge >= 0) {
    throw new Error('Invalid charges: cation must be positive, anion must be negative');
  }

  // Use absolute values for calculation
  const cationAbs = Math.abs(cationCharge);
  const anionAbs = Math.abs(anionCharge);

  // Find LCM of charges
  const lcmValue = lcm(cationAbs, anionAbs);

  // Calculate subscripts
  const cationCount = lcmValue / cationAbs;
  const anionCount = lcmValue / anionAbs;

  return { cationCount, anionCount };
}

/**
 * Create an ionic compound from a cation and anion
 */
export function createIonicCompound(cation: Ion, anion: Ion): IonicCompound {
  if (!cation.isIonized || !anion.isIonized) {
    throw new Error('Both ions must be ionized before forming a compound');
  }

  if (cation.charge <= 0) {
    throw new Error('Cation must have a positive charge');
  }

  if (anion.charge >= 0) {
    throw new Error('Anion must have a negative charge');
  }

  // Balance charges
  const { cationCount, anionCount } = balanceCharges(cation.charge, anion.charge);

  // Update ion counts
  const balancedCation: Ion = { ...cation, count: cationCount };
  const balancedAnion: Ion = { ...anion, count: anionCount };

  // Determine if compound is balanced
  const totalCharge = cation.charge * cationCount + anion.charge * anionCount;
  const isBalanced = totalCharge === 0;

  return {
    id: `compound-${Date.now()}`,
    cations: [balancedCation],
    anions: [balancedAnion],
    formula: '', // Will be generated by compoundEngine
    isBalanced,
    formulaUnit: {
      cation: cation.element || cation.polyatomicId || '',
      anion: anion.element || anion.polyatomicId || '',
      cationCount,
      anionCount,
    },
  };
}

/**
 * Calculate the size of an ion for visualization (in pixels)
 * Based on ionic radius data
 */
export function getIonSize(ion: Ion): number {
  let ionKey = '';

  if (ion.polyatomicId) {
    // Polyatomic ions get a standard size
    return 60; // Larger to fit formula
  } else if (ion.element) {
    // Monoatomic ion
    const chargeStr = ion.charge > 0 ? `${ion.charge}+` : `${Math.abs(ion.charge)}-`;
    ionKey = `${ion.element}${chargeStr}`;
  }

  const radiusPm = IONIC_RADII[ionKey];
  if (radiusPm) {
    // Scale radius to pixels (arbitrary scaling factor for visibility)
    return Math.max(40, Math.min(80, radiusPm / 2));
  }

  // Default size
  return 50;
}

/**
 * Get the color for an ion
 */
export function getIonColor(ion: Ion): string {
  if (ion.polyatomicId) {
    const polyatomic = POLYATOMIC_IONS[ion.polyatomicId];
    return polyatomic?.color || '#94A3B8';
  } else if (ion.element) {
    const elementInfo = METALS[ion.element] || NONMETALS[ion.element];
    return elementInfo?.color || '#94A3B8';
  }
  return '#94A3B8';
}

/**
 * Get the label for an ion (e.g., "Na⁺", "Cl⁻", "SO₄²⁻")
 */
export function getIonLabel(ion: Ion): string {
  if (ion.polyatomicId) {
    const polyatomic = POLYATOMIC_IONS[ion.polyatomicId];
    return polyatomic?.formula || '';
  } else if (ion.element) {
    if (!ion.isIonized) {
      return ion.element;
    }

    const charge = ion.charge;
    if (charge === 0) {
      return ion.element;
    }

    const chargeAbs = Math.abs(charge);
    const chargeSign = charge > 0 ? '+' : '-';

    // Use superscript numbers
    const superscriptNumbers: Record<number, string> = {
      1: '⁺',
      2: '²⁺',
      3: '³⁺',
      4: '⁴⁺',
    };
    const superscriptNeg: Record<number, string> = {
      1: '⁻',
      2: '²⁻',
      3: '³⁻',
      4: '⁴⁻',
    };

    if (charge > 0) {
      return `${ion.element}${superscriptNumbers[chargeAbs] || `${chargeAbs}${chargeSign}`}`;
    } else {
      return `${ion.element}${superscriptNeg[chargeAbs] || `${chargeAbs}${chargeSign}`}`;
    }
  }
  return '';
}

/**
 * Validate ionic compound formation
 */
export interface ValidationResult {
  valid: boolean;
  errors: string[];
  warnings: string[];
}

export function validateIonicCompound(compound: IonicCompound): ValidationResult {
  const errors: string[] = [];
  const warnings: string[] = [];

  // Check if compound has both cations and anions
  if (compound.cations.length === 0) {
    errors.push('Compound must have at least one cation (positive ion)');
  }
  if (compound.anions.length === 0) {
    errors.push('Compound must have at least one anion (negative ion)');
  }

  // Check if charges are balanced
  if (!compound.isBalanced) {
    errors.push('Total charge must equal zero (charges not balanced)');
  }

  // Check if all ions are ionized
  const allIonized = [...compound.cations, ...compound.anions].every(ion => ion.isIonized);
  if (!allIonized) {
    warnings.push('All atoms must be ionized before forming a stable compound');
  }

  return {
    valid: errors.length === 0,
    errors,
    warnings,
  };
}

/**
 * Get electron configuration for an element (simplified for visualization)
 */
export function getElectronConfig(element: string, isIonized: boolean, charge: number): string {
  const elementInfo = METALS[element] || NONMETALS[element];
  if (!elementInfo) return '';

  // Simplified electron configurations (valence only)
  const configs: Record<string, string> = {
    // Metals
    Na: isIonized && charge === 1 ? '2,8' : '2,8,1',
    K: isIonized && charge === 1 ? '2,8,8' : '2,8,8,1',
    Mg: isIonized && charge === 2 ? '2,8' : '2,8,2',
    Ca: isIonized && charge === 2 ? '2,8,8' : '2,8,8,2',
    Al: isIonized && charge === 3 ? '2,8' : '2,8,3',

    // Non-metals
    Cl: isIonized && charge === -1 ? '2,8,8' : '2,8,7',
    O: isIonized && charge === -2 ? '2,8' : '2,6',
    F: isIonized && charge === -1 ? '2,8' : '2,7',
    S: isIonized && charge === -2 ? '2,8,8' : '2,8,6',
    N: isIonized && charge === -3 ? '2,8' : '2,5',
    Br: isIonized && charge === -1 ? '2,8,18,8' : '2,8,18,7',
  };

  return configs[element] || '';
}

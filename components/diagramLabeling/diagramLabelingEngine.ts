import { DiagramPreset, DiagramEvaluation, CalloutAttempt } from './diagramLabelingTypes';

/**
 * Normalizes input text for resilient student answer checking.
 */
export function normalizeAnswer(text: string): string {
  return text
    .toLowerCase()
    .replace(/^(the|a|an)\s+/i, '')
    .replace(/[^a-z0-9]/g, '')
    .trim();
}

/**
 * Checks whether a user guess matches canonical label or any recognized synonyms.
 */
export function isAnswerCorrect(
  guess: string,
  canonicalLabel: string,
  acceptableAnswers: string[] = []
): boolean {
  if (!guess || !guess.trim()) return false;
  const normGuess = normalizeAnswer(guess);
  if (!normGuess) return false;

  const normCanonical = normalizeAnswer(canonicalLabel);
  if (normGuess === normCanonical) return true;

  return acceptableAnswers.some(alt => normalizeAnswer(alt) === normGuess);
}

/**
 * Evaluates all callout attempts for a diagram preset.
 */
export function evaluateDiagramAttempts(
  preset: DiagramPreset,
  userGuesses: Record<string, string>
): DiagramEvaluation {
  const attempts: Record<string, CalloutAttempt> = {};
  let correctCount = 0;

  preset.callouts.forEach(callout => {
    const guess = userGuesses[callout.id] || '';
    const correct = isAnswerCorrect(guess, callout.label, callout.acceptableAnswers);

    if (correct) correctCount++;

    let feedback = '';
    if (!guess.trim()) {
      feedback = 'Unanswered.';
    } else if (correct) {
      feedback = `Accurate identification: ${callout.label}.`;
    } else {
      feedback = `Incorrect. Expected: ${callout.label}.`;
    }

    attempts[callout.id] = {
      calloutId: callout.id,
      userGuess: guess,
      isCorrect: correct,
      score: correct ? 1 : 0,
      feedback,
    };
  });

  const totalCallouts = preset.callouts.length;
  const scorePercentage = totalCallouts > 0 ? Math.round((correctCount / totalCallouts) * 100) : 0;
  const allComplete = preset.callouts.every(c => !!userGuesses[c.id]?.trim());

  return {
    totalCallouts,
    correctCount,
    scorePercentage,
    attempts,
    allComplete,
  };
}

/**
 * Exports complete diagram structure and study guide to Markdown.
 */
export function exportDiagramNotesToMarkdown(
  preset: DiagramPreset,
  evaluation?: DiagramEvaluation
): string {
  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });

  let md = `# Visual Diagram Guide: ${preset.title}\n\n`;
  md += `**Course:** ${preset.course}  \n`;
  md += `**Topic:** ${preset.topic}  \n`;
  md += `**Date:** ${dateStr}  \n\n`;
  md += `> ${preset.description}\n\n`;

  md += `## Anatomical & Structural Index (${preset.callouts.length} Callouts)\n\n`;
  md += `| # | Feature / Region | Functional Role & Notes |\n`;
  md += `|---|---|---|\n`;

  preset.callouts.forEach(c => {
    md += `| **${c.number}** | **${c.label}** | ${c.description || c.hint || 'Key functional domain'} |\n`;
  });
  md += `\n`;

  if (evaluation) {
    md += `## Quiz Performance Summary\n\n`;
    md += `- **Mastery Score:** ${evaluation.scorePercentage}% (${evaluation.correctCount}/${evaluation.totalCallouts} identified)\n\n`;

    md += `### Detailed Results\n\n`;
    preset.callouts.forEach(c => {
      const att = evaluation.attempts[c.id];
      const icon = att?.isCorrect ? '✅' : '❌';
      const userText = att?.userGuess ? `Your answer: "${att.userGuess}"` : 'Not answered';
      md += `- ${icon} **Callout ${c.number} (${c.label}):** ${userText}\n`;
      if (att && !att.isCorrect && att.feedback) {
        md += `  - _${att.feedback}_\n`;
      }
    });
    md += `\n`;
  }

  md += `---\n_Generated by Science Practice Partner (https://sciencepractice.app)_\n`;
  return md;
}

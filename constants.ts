export const parseQuizData = (markdown: string): Record<string, Record<string, string[]>> => {
  if (!markdown) {
    console.warn("parseQuizData received empty or undefined markdown");
    return {};
  }
  const lines = markdown.split('\n').filter(l => l.trim().length > 0);
  const data: Record<string, Record<string, string[]>> = {};

  let currentUnit = '';

  lines.forEach(line => {
    if (line.startsWith('# **')) {
      // Unit Header
      currentUnit = line.replace('# **', '').replace('**', '').trim();
      data[currentUnit] = {};
    } else if (line.startsWith('### **')) {
      // Topic Header
      const topic = line.replace('### **', '').replace('**', '').trim();
      if (currentUnit) {
        // We use the topic as both key and value container for now
        // In this app, topics are just strings, but the structure supports sub-questions if needed later
        data[currentUnit][topic] = [];
      }
    }
  });

  return data;
};

